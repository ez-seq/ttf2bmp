package converter

import (
	"fmt"
	"image"
	"os"
	"path/filepath"
	"strings"
)

// Limits of the Microchip Graphics Library font layout (FONT_HEADER and GLYPH_ENTRY in
// its Primitive.h, as written by Microchip's Graphics Resource Converter): GLYPH_ENTRY
// holds the width in one byte and the offset in three. Codes are limited to 8 bits too,
// as renderers derived from that library commonly index glyphs by an unsigned char.
const (
	cMaxChar   = 0xFF
	cMaxWidth  = 0xFF
	cMaxHeight = 0xFFFF
	cMaxOffset = 0xFFFFFF

	cHeaderSize = 8 // sizeof(FONT_HEADER)
	cGlyphSize  = 4 // sizeof(GLYPH_ENTRY)
)

// cGlyph is one character of the font as laid out in the atlas.
type cGlyph struct {
	x, width int
}

// cFont is everything writeCSource needs besides the atlas image.
type cFont struct {
	fontPath  string
	size      int
	hinting   string
	stroke    float64
	bpp       int
	threshold float64
	height    int
	glyphs    map[rune]cGlyph
}

// CIdentifier turns a file name into a C identifier: every character that is not a
// letter or digit becomes '_', and a leading digit is prefixed with '_'.
func CIdentifier(name string) string {
	var b strings.Builder
	for _, r := range name {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	id := b.String()
	if id == "" || (id[0] >= '0' && id[0] <= '9') {
		id = "_" + id
	}
	return id
}

// writeCSource writes outPrefix.c and outPrefix.h: the font as a const, flash-resident
// Microchip Graphics Library font (FONT_HEADER, GLYPH_ENTRY table, glyph bitmaps), the
// layout that library's SetFont/OutChar/GetTextWidth read directly, with no runtime
// decompression. The font is exported through a handle, SFontHandle, a struct whose
// only member is the font's address, as an opaque void pointer.
//
// The font covers one contiguous range, from the lowest to the highest character
// requested. Characters in between that were not requested, or are not in the face,
// get an empty glyph of width 0. Each glyph is a cell of its advance width and the full
// line height, the same cell as in the atlas. Rows are packed from the least
// significant bit, pixel by pixel, bpp bits each, and padded to a whole byte.
func writeCSource(outPrefix string, img *image.RGBA, f cFont) error {
	if len(f.glyphs) == 0 {
		return fmt.Errorf("no glyphs to write")
	}
	if f.height > cMaxHeight {
		return fmt.Errorf("line height %d: the font header holds at most %d", f.height, cMaxHeight)
	}
	first, last := rune(-1), rune(-1)
	for r, g := range f.glyphs {
		if r > cMaxChar {
			return fmt.Errorf("character %q (U+%04X): the font format holds codes up to 0x%02X only", r, r, cMaxChar)
		}
		if g.width > cMaxWidth {
			return fmt.Errorf("character %q: width %d exceeds %d", r, g.width, cMaxWidth)
		}
		if first < 0 || r < first {
			first = r
		}
		if r > last {
			last = r
		}
	}
	count := int(last-first) + 1

	type entry struct {
		char   rune
		width  int
		offset int
		rows   [][]byte
	}
	entries := make([]entry, 0, count)
	offset := cHeaderSize + cGlyphSize*count
	dataSize := 0
	for r := first; r <= last; r++ {
		g, ok := f.glyphs[r]
		e := entry{char: r, offset: offset}
		if ok {
			e.width = g.width
			stride := (g.width*f.bpp + 7) / 8
			for y := 0; y < f.height; y++ {
				row := make([]byte, stride)
				for i := 0; i < g.width; i++ {
					a := img.RGBAAt(g.x+i, y).A
					bit := i * f.bpp
					row[bit/8] |= level(a, f.bpp, f.threshold) << (bit % 8)
				}
				e.rows = append(e.rows, row)
			}
			offset += stride * f.height
			dataSize += stride * f.height
		}
		entries = append(entries, e)
	}
	if offset > cMaxOffset {
		return fmt.Errorf("font data is %d bytes: glyph offsets hold at most %d", offset, cMaxOffset)
	}

	base := filepath.Base(outPrefix)
	id := CIdentifier(base)
	bppCode := map[int]int{1: 0, 2: 1, 4: 2, 8: 3}[f.bpp]

	desc := []string{
		fmt.Sprintf("Generated by ttf2bmp from %s at %dpx.", filepath.Base(f.fontPath), f.size),
		fmt.Sprintf("%d bpp, hinting %s", f.bpp, f.hinting),
	}
	if f.bpp == 1 {
		desc[1] += fmt.Sprintf(", threshold %g", f.threshold)
	}
	if f.stroke > 0 {
		desc[1] += fmt.Sprintf(", stroke %gpx", f.stroke)
	}
	desc[1] += fmt.Sprintf(", height %d, chars 0x%02X-0x%02X.", f.height, first, last)
	if f.bpp > 1 {
		desc = append(desc, "Note: the font renderer must support this bpp (FONT_HEADER.bpp).")
	}
	desc = append(desc, "Do not edit by hand; regenerate with ttf2bmp.")

	if err := writeFile(outPrefix+".h", func(w *strings.Builder) {
		for _, line := range desc {
			fmt.Fprintf(w, "// %s\n", line)
		}
		fmt.Fprintf(w, "#pragma once\n\n")
		fmt.Fprintf(w, "extern void * gpOpaqueFont_%s;\n", id)
	}); err != nil {
		return err
	}

	typeName := "SFontData_" + id
	return writeFile(outPrefix+".c", func(w *strings.Builder) {
		for _, line := range desc {
			fmt.Fprintf(w, "// %s\n", line)
		}
		fmt.Fprintf(w, "#include <stddef.h>\n\n")
		fmt.Fprintf(w, "#include \"%s.h\"\n", base)
		fmt.Fprintf(w, "#include \"Primitive.h\"\n\n\n")

		fmt.Fprintf(w, "typedef struct %s\n{\n", typeName)
		fmt.Fprintf(w, "\tFONT_HEADER header;\n")
		fmt.Fprintf(w, "\tGLYPH_ENTRY glyphs[%d];\n", count)
		if dataSize > 0 {
			fmt.Fprintf(w, "\tunsigned char bitmaps[%d];\n", dataSize)
		}
		fmt.Fprintf(w, "} %s;\n\n", typeName)

		fmt.Fprintf(w, "_Static_assert(sizeof(FONT_HEADER) == %d, \"FONT_HEADER layout\");\n", cHeaderSize)
		fmt.Fprintf(w, "_Static_assert(sizeof(GLYPH_ENTRY) == %d, \"GLYPH_ENTRY layout\");\n", cGlyphSize)
		if dataSize > 0 {
			fmt.Fprintf(w, "_Static_assert(offsetof(%s, bitmaps) == %d, \"glyph offsets assume no padding\");\n", typeName, cHeaderSize+cGlyphSize*count)
		}
		fmt.Fprintf(w, "\n")

		fmt.Fprintf(w, "static const %s gFontData_%s =\n{\n", typeName, id)
		fmt.Fprintf(w, "\t.header =\n\t{\n")
		fmt.Fprintf(w, "\t\t.fontID = 0,\n")
		fmt.Fprintf(w, "\t\t.extendedGlyphEntry = 0,\n")
		fmt.Fprintf(w, "\t\t.res1 = 0,\n")
		fmt.Fprintf(w, "\t\t.bpp = %d,\t// %d bpp\n", bppCode, f.bpp)
		fmt.Fprintf(w, "\t\t.orientation = 0,\n")
		fmt.Fprintf(w, "\t\t.res2 = 0,\n")
		fmt.Fprintf(w, "\t\t.firstChar = 0x%02X,\n", first)
		fmt.Fprintf(w, "\t\t.lastChar = 0x%02X,\n", last)
		fmt.Fprintf(w, "\t\t.height = %d,\n", f.height)
		fmt.Fprintf(w, "\t},\n")

		fmt.Fprintf(w, "\t.glyphs =\n\t{\n")
		for _, e := range entries {
			fmt.Fprintf(w, "\t\t{ %3d, 0x%02X, 0x%04X },\t// %s\n", e.width, e.offset&0xFF, e.offset>>8, charLabel(e.char, e.rows != nil))
		}
		fmt.Fprintf(w, "\t},\n")

		if dataSize > 0 {
			fmt.Fprintf(w, "\t.bitmaps =\n\t{\n")
			for _, e := range entries {
				if e.rows == nil {
					continue
				}
				fmt.Fprintf(w, "\t\t// %s, width %d\n", charLabel(e.char, true), e.width)
				for _, row := range e.rows {
					hex := make([]string, len(row))
					for i, v := range row {
						hex[i] = fmt.Sprintf("0x%02X,", v)
					}
					fmt.Fprintf(w, "\t\t%s\t// %s\n", strings.Join(hex, " "), rowArt(row, e.width, f.bpp))
				}
			}
			fmt.Fprintf(w, "\t},\n")
		}
		fmt.Fprintf(w, "};\n\n")

		fmt.Fprintf(w, "static const SFontHandle gFontHandle_%s = { (const char *) &gFontData_%s };\n", id, id)
		fmt.Fprintf(w, "void * gpOpaqueFont_%s = (void *) &gFontHandle_%s;\n", id, id)
	})
}

// charLabel names a character in a C line comment. The character is quoted, so a
// backslash never ends the line (which would splice the next line into the comment),
// and anything outside printable ASCII is given by its code only.
func charLabel(r rune, present bool) string {
	var s string
	switch {
	case r == '\\':
		s = fmt.Sprintf("0x%02X '\\\\'", r)
	case r >= 0x20 && r < 0x7F:
		s = fmt.Sprintf("0x%02X '%c'", r, r)
	default:
		s = fmt.Sprintf("0x%02X", r)
	}
	if !present {
		s += " (empty)"
	}
	return s
}

// rowArt draws one bitmap row as text: '.' is off, '#' full ink, and the levels in
// between are shaded.
func rowArt(row []byte, width, bpp int) string {
	const ramp = ".:-=+*%#"
	maxLevel := 1<<bpp - 1
	mask := byte(maxLevel)
	var b strings.Builder
	for i := 0; i < width; i++ {
		bit := i * bpp
		v := int((row[bit/8] >> (bit % 8)) & mask)
		b.WriteByte(ramp[(v*(len(ramp)-1)+maxLevel/2)/maxLevel])
	}
	return b.String()
}

// writeFile writes the text fill builds to path.
func writeFile(path string, fill func(w *strings.Builder)) error {
	var b strings.Builder
	fill(&b)
	return os.WriteFile(path, []byte(b.String()), 0644)
}
